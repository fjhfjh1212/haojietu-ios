#!/usr/bin/env python3
"""Build-time patch for the 好截图2 iOS alternate app icons.

Runs on Codemagic (macOS) AFTER `cap add ios` / `cap sync ios` and AFTER
`capacitor-assets generate`, BEFORE `pod install`:

1. Adds the local AlternateIcon Capacitor plugin pod to ios/App/Podfile.
2. Creates Assets.xcassets image sets AppIcon-wechat / AppIcon-alipay from
   the pre-sized PNGs in assets/ (original Android launcher icons:
   wechat.png / alipay.png, 192x192, upscaled at repo build time).
3. Patches ios/App/App/Info.plist with CFBundleAlternateIcons.

Alternate icon sizes (iPhone + iPad):
  120 = 60pt @2x, 152 = 76pt @2x, 167 = 83.5pt @2x, 180 = 60pt @3x.
The primary icon （微截图2) is the normal AppIcon, generated by
@capacitor/assets from assets/icon.png.

Usage: python3 scripts/patch_alternate_icons.py   (run from repo root)
Idempotent: safe to run twice.
"""
import json
import plistlib
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
APP_DIR = ROOT / "ios" / "App"
XCASSETS = APP_DIR / "App" / "Assets.xcassets"
PLIST = APP_DIR / "App" / "Info.plist"
PODFILE = APP_DIR / "Podfile"

POD_LINE = "  pod 'HaoJieTuAlternateIcon', :path => '../../plugins/alternate-icon'"

# (alternate icon name, source prefix in assets/)
ALTERNATES = [
    ("wechat", "alt-wechat"),
    ("alipay", "alt-alipay"),
]

# size -> (idiom, scale) for the imageset Contents.json
SIZES = [
    (120, "iphone", "2x"),
    (180, "iphone", "3x"),
    (152, "ipad", "2x"),
    (167, "ipad", "2x"),
]


def patch_podfile():
    text = PODFILE.read_text()
    if "HaoJieTuAlternateIcon" in text:
        print("Podfile: plugin pod already present")
        return
    if "capacitor_pods" not in text:
        raise SystemExit("Podfile: could not find 'capacitor_pods' marker")
    text = text.replace("capacitor_pods", "capacitor_pods\n" + POD_LINE, 1)
    PODFILE.write_text(text)
    print("Podfile: added HaoJieTuAlternateIcon pod")


def make_imageset(name, prefix):
    d = XCASSETS / f"AppIcon-{name}.imageset"
    d.mkdir(parents=True, exist_ok=True)
    images = []
    for size, idiom, scale in SIZES:
        src = ASSETS / f"{prefix}-{size}.png"
        if not src.exists():
            raise SystemExit(f"missing alternate icon source: {src}")
        dst_name = f"AppIcon-{name}-{size}.png"
        shutil.copyfile(src, d / dst_name)
        pt = size / int(scale[0])
        pt_s = ('%g' % pt)
        images.append({
            "filename": dst_name,
            "idiom": idiom,
            "scale": scale,
            "size": f"{pt_s}x{pt_s}",
        })
    contents = {
        "images": images,
        "info": {"author": "xcode", "version": 1},
    }
    (d / "Contents.json").write_text(json.dumps(contents, indent=2))
    print(f"imageset: AppIcon-{name} ({len(images)} sizes)")


def patch_plist():
    with open(PLIST, "rb") as f:
        plist = plistlib.load(f)
    icons = plist.setdefault("CFBundleIcons", {})
    primary = icons.setdefault("CFBundlePrimaryIcon", {})
    primary.setdefault("CFBundleIconFiles", ["AppIcon"])
    primary.setdefault("CFBundleIconName", "AppIcon")
    alternates = icons.setdefault("CFBundleAlternateIcons", {})
    for name, _prefix in ALTERNATES:
        alternates[name] = {"CFBundleIconFiles": [f"AppIcon-{name}"]}
    with open(PLIST, "wb") as f:
        plistlib.dump(plist, f)
    print("Info.plist: CFBundleAlternateIcons =", sorted(alternates.keys()))


def main():
    for p in (XCASSETS, PLIST, PODFILE):
        if not p.exists():
            raise SystemExit(f"missing (run after cap add ios): {p}")
    patch_podfile()
    for name, prefix in ALTERNATES:
        make_imageset(name, prefix)
    patch_plist()
    print("alternate icons patch OK")


if __name__ == "__main__":
    sys.exit(main())
